import { ExportOptions, SubtitleCue, SubtitleFormat } from "./types";
import { secondsToTimestamp } from "./parser";

/**
 * Format a cue's text according to export mode
 */
function resolveCueText(cue: SubtitleCue, mode: ExportOptions["mode"]): string {
  const original = cue.originalText.trim();
  const translated = (cue.translatedText || cue.originalText).trim();

  switch (mode) {
    case "original":
      return original;
    case "translated":
      return translated;
    case "bilingual-stacked":
      return `${translated}\n${original}`;
    case "bilingual-inline":
      return `${translated} (${original})`;
    default:
      return translated;
  }
}

/**
 * Serialize cues to SRT format
 */
export function serializeSRT(cues: SubtitleCue[], options: ExportOptions): string {
  const offsetSeconds = (options.timeOffsetMs || 0) / 1000;
  const blocks: string[] = [];

  cues.forEach((cue, index) => {
    const startSec = Math.max(0, cue.startSeconds + offsetSeconds);
    const endSec = Math.max(startSec + 0.1, cue.endSeconds + offsetSeconds);

    const startTimestamp = secondsToTimestamp(startSec, "srt");
    const endTimestamp = secondsToTimestamp(endSec, "srt");
    const text = resolveCueText(cue, options.mode);

    blocks.push(`${index + 1}\n${startTimestamp} --> ${endTimestamp}\n${text}`);
  });

  let result = blocks.join("\n\n");
  if (options.normalizeLineBreaks) {
    result = result.replace(/\r\n/g, "\n").replace(/\n/g, "\r\n");
  }

  return result + (options.normalizeLineBreaks ? "\r\n" : "\n");
}

/**
 * Serialize cues to WebVTT format
 */
export function serializeVTT(
  cues: SubtitleCue[],
  options: ExportOptions,
  header = "WEBVTT - Generated by SubLingo Subtitle Studio"
): string {
  const offsetSeconds = (options.timeOffsetMs || 0) / 1000;
  const blocks: string[] = [];

  cues.forEach((cue, index) => {
    const startSec = Math.max(0, cue.startSeconds + offsetSeconds);
    const endSec = Math.max(startSec + 0.1, cue.endSeconds + offsetSeconds);

    const startTimestamp = secondsToTimestamp(startSec, "vtt");
    const endTimestamp = secondsToTimestamp(endSec, "vtt");
    const settingsStr = cue.settings ? ` ${cue.settings}` : "";
    const text = resolveCueText(cue, options.mode);

    blocks.push(`${index + 1}\n${startTimestamp} --> ${endTimestamp}${settingsStr}\n${text}`);
  });

  const fullHeader = header.startsWith("WEBVTT") ? header : `WEBVTT\n${header}`;
  let result = `${fullHeader}\n\n${blocks.join("\n\n")}`;

  if (options.normalizeLineBreaks) {
    result = result.replace(/\r\n/g, "\n").replace(/\n/g, "\r\n");
  }

  return result + (options.normalizeLineBreaks ? "\r\n" : "\n");
}

/**
 * Universal export serializer
 */
export function serializeSubtitles(
  cues: SubtitleCue[],
  options: ExportOptions,
  vttHeader?: string
): { content: string; mimeType: string; extension: string } {
  if (options.format === "vtt") {
    return {
      content: serializeVTT(cues, options, vttHeader),
      mimeType: "text/vtt;charset=utf-8",
      extension: "vtt",
    };
  } else {
    return {
      content: serializeSRT(cues, options),
      mimeType: "application/x-subrip;charset=utf-8",
      extension: "srt",
    };
  }
}
